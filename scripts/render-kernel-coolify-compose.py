#!/usr/bin/env python3
"""Render the Git-based Coolify Standard profile as one secret-free Compose file."""

from __future__ import annotations

import argparse
import json
import os
import re
import subprocess
import sys
import tempfile
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
OUTPUT = ROOT / "docker-compose.kernel-coolify.yml"
# Keep this aligned with:
# standard --coolify --separate-api-worker-logins --scheduler-role --zitadel
COMPOSE_FILES = (
    "docker-compose.kernel-candidate.yml",
    "docker-compose.kernel-standard.yml",
    "docker-compose.kernel-runtime-role.yml",
    "docker-compose.kernel-worker-runtime-role.yml",
    "docker-compose.kernel-proxy.yml",
    "docker-compose.kernel-oidc.yml",
    "docker-compose.kernel-zitadel.yml",
    "docker-compose.kernel-scheduler-role.yml",
    "docker-compose.kernel-worker-runtime-supervisor.yml",
    "docker-compose.kernel-coolify-network.yml",
    "docker-compose.kernel-coolify-zitadel.yml",
    "docker-compose.kernel-coolify-build.yml",
    "docker-compose.kernel-coolify-media.yml",
)
HEADER = "# Generated by scripts/render-kernel-coolify-compose.py; do not edit directly.\n"
ENVIRONMENT_KEY = re.compile(r"^[A-Za-z_][A-Za-z0-9_]*$")
ENVIRONMENT_KEY_INVENTORY = ROOT / "config/kernel/coolify-environment-key-inventory.json"
ENVIRONMENT_KEY_SOURCES = (ROOT / ".env.example", ROOT / ".env.sops")


def _compose_command(files: tuple[str, ...], output_format: str) -> list[str]:
    command = [
        "docker",
        "compose",
        "--project-directory",
        str(ROOT),
        "--env-file",
        "/dev/null",
        "-p",
        "kokonut-kernel-coolify",
    ]
    for filename in files:
        command.extend(("-f", "-" if filename == "-" else str(ROOT / filename)))
    command.extend(("config", "--no-interpolate", "--no-path-resolution", "--format", output_format))
    return command


def _run_compose_config(files: tuple[str, ...], output_format: str, *, input_text: str | None = None) -> str:
    command = _compose_command(files, output_format)
    try:
        result = subprocess.run(command, cwd=ROOT, check=False, capture_output=True, text=True, input=input_text)
    except FileNotFoundError as exc:
        raise RuntimeError("Docker Compose v2 is required to render the Coolify manifest") from exc
    if result.returncode:
        detail = result.stderr.strip() or "Docker Compose could not render the selected profile"
        raise RuntimeError(detail)
    return result.stdout


def _normalized_config(files: tuple[str, ...]) -> object:
    try:
        return json.loads(_run_compose_config(files, "json"))
    except json.JSONDecodeError as exc:
        raise RuntimeError("Docker Compose returned invalid JSON while checking the manifest") from exc


def _validate_coolify_interpolation(config: object) -> None:
    # The current Coolify Compose parser does not support Docker Compose's :+
    # operator and treats the whole expression as an environment-variable key.
    serialized = json.dumps(config)
    unsupported = sorted(
        set(re.findall(r"\$\{([A-Za-z_][A-Za-z0-9_]*):\+[^}]*\}", serialized))
    )
    if unsupported:
        names = ", ".join(unsupported)
        raise RuntimeError(
            "Coolify's current Compose parser does not support the :+ interpolation "
            f"operator (variables: {names}); use an explicit configuration flag"
        )


def _validate_coolify_build_policy(config: object) -> None:
    if not isinstance(config, dict):
        raise RuntimeError("Coolify Compose configuration must be a mapping")
    services = config.get("services")
    if not isinstance(services, dict):
        raise RuntimeError("Coolify Compose configuration has no services mapping")
    for name in ("app", "worker"):
        service = services.get(name)
        if not isinstance(service, dict) or not isinstance(service.get("build"), dict):
            raise RuntimeError(f"Coolify {name} service must build from the Git checkout")
        if service.get("pull_policy") != "build":
            raise RuntimeError(f"Coolify {name} service must rebuild its local image from source")


def _environment_entries(environment: object) -> list[tuple[str, str | None]]:
    if isinstance(environment, dict):
        return [(str(key), None if value is None else str(value)) for key, value in environment.items()]
    if isinstance(environment, list):
        entries: list[tuple[str, str | None]] = []
        for item in environment:
            if not isinstance(item, str):
                raise RuntimeError("Coolify Compose environment list entries must be strings")
            key, separator, value = item.partition("=")
            entries.append((key, value if separator else None))
        return entries
    raise RuntimeError("Coolify Compose environment must be a mapping or list")


def _environment_keys_from_file(path: Path) -> set[str]:
    keys: set[str] = set()
    try:
        lines = path.read_text(encoding="utf-8").splitlines()
    except OSError as exc:
        raise RuntimeError(f"Could not read Coolify environment key source {path.relative_to(ROOT)}") from exc
    for raw_line in lines:
        line = raw_line.strip()
        if not line or line.startswith("#") or "=" not in line:
            continue
        key = line.partition("=")[0].strip()
        if ENVIRONMENT_KEY.fullmatch(key) and not key.startswith("sops_"):
            keys.add(key)
    return keys


def _coolify_environment_key_names() -> set[str]:
    try:
        inventory = json.loads(ENVIRONMENT_KEY_INVENTORY.read_text(encoding="utf-8"))
    except (OSError, json.JSONDecodeError) as exc:
        raise RuntimeError("Coolify environment key inventory is missing or invalid") from exc
    if not isinstance(inventory, dict) or inventory.get("format_version") != 1:
        raise RuntimeError("Coolify environment key inventory has an unsupported format")
    raw_keys = inventory.get("keys")
    if not isinstance(raw_keys, list) or any(not isinstance(key, str) for key in raw_keys):
        raise RuntimeError("Coolify environment key inventory must contain a string key list")
    if any(not ENVIRONMENT_KEY.fullmatch(key) for key in raw_keys) or len(set(raw_keys)) != len(raw_keys):
        raise RuntimeError("Coolify environment key inventory contains invalid or duplicate names")
    keys = set(raw_keys)
    for source in ENVIRONMENT_KEY_SOURCES:
        missing = _environment_keys_from_file(source) - keys
        if missing:
            names = ", ".join(sorted(missing))
            raise RuntimeError(
                f"Coolify environment key inventory is missing names from {source.relative_to(ROOT)}: {names}"
            )
    return keys


def _isolate_coolify_service_environments(services: dict[str, object]) -> set[str]:
    """Override Coolify's app-wide env_file values unless a service declares a need."""
    shared_environment_keys = _coolify_environment_key_names()
    service_environments: dict[str, dict[str, str | None]] = {}
    for service_name, service in services.items():
        if not isinstance(service, dict):
            raise RuntimeError(f"Coolify service {service_name} must be a mapping")
        environment = dict(_environment_entries(service.get("environment", {})))
        service_environments[service_name] = environment
        shared_environment_keys.update(environment)
    for service_name, service in services.items():
        environment = service_environments[service_name]
        for key in shared_environment_keys:
            environment.setdefault(key, "")
        service["environment"] = environment
    return shared_environment_keys


def _coolify_config(files: tuple[str, ...]) -> object:
    config = _normalized_config(files)
    if not isinstance(config, dict) or not isinstance(config.get("services"), dict):
        raise RuntimeError("Coolify Compose configuration must contain services")
    services = config["services"]
    app = services.get("app")
    worker = services.get("worker")
    if not isinstance(app, dict) or not isinstance(worker, dict):
        raise RuntimeError("Coolify Compose configuration must contain app and worker services")

    shared_environment_keys = _isolate_coolify_service_environments(services)
    for service_name, service in services.items():
        environment = dict(_environment_entries(service.get("environment", {})))
        if not shared_environment_keys.issubset(environment):
            raise RuntimeError(f"Coolify service {service_name} does not isolate every shared environment key")
        if service_name == "app":
            continue
        if any(value not in (None, "") for key, value in environment.items() if key.startswith("MOBILE_MEDIA_")):
            raise RuntimeError(f"Coolify service {service_name} must not receive Collector media settings")
    return config


def _render_coolify_yaml(config: object) -> str:
    return _run_compose_config(("-",), "yaml", input_text=json.dumps(config))


def _normalized_checked_in() -> object:
    if not OUTPUT.is_file():
        return None
    try:
        return json.loads(_run_compose_config((OUTPUT.name,), "json"))
    except json.JSONDecodeError as exc:
        raise RuntimeError("Docker Compose returned invalid JSON while checking the Coolify manifest") from exc


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--check",
        action="store_true",
        help="fail if the checked-in Coolify manifest is stale; do not write files",
    )
    args = parser.parse_args()

    if args.check:
        try:
            generated = _coolify_config(COMPOSE_FILES)
            _validate_coolify_interpolation(generated)
            _validate_coolify_build_policy(generated)
            checked_in = _normalized_checked_in()
            if checked_in is not None:
                _validate_coolify_interpolation(checked_in)
                _validate_coolify_build_policy(checked_in)
        except RuntimeError as exc:
            print(f"error: {exc}", file=sys.stderr)
            return 2
        if checked_in is None or checked_in != generated:
            print(f"{OUTPUT.relative_to(ROOT)} is stale; rerun {Path(__file__).name}", file=sys.stderr)
            return 1
        print(f"{OUTPUT.relative_to(ROOT)} matches its Compose overlays")
        return 0

    try:
        generated = _coolify_config(COMPOSE_FILES)
        _validate_coolify_interpolation(generated)
        _validate_coolify_build_policy(generated)
        compose_yaml = _render_coolify_yaml(generated)
        rendered = HEADER + compose_yaml
    except RuntimeError as exc:
        print(f"error: {exc}", file=sys.stderr)
        return 2

    temp_path: Path | None = None
    try:
        with tempfile.NamedTemporaryFile(
            mode="w", encoding="utf-8", dir=ROOT, prefix=".kernel-coolify-", delete=False
        ) as temp_file:
            temp_file.write(rendered)
            temp_path = Path(temp_file.name)
        os.replace(temp_path, OUTPUT)
    except OSError as exc:
        print(f"error: could not write {OUTPUT.relative_to(ROOT)}: {exc}", file=sys.stderr)
        return 2
    finally:
        if temp_path is not None and temp_path.exists():
            temp_path.unlink()

    print(f"Rendered {OUTPUT.relative_to(ROOT)} without resolving environment variables")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
