#!/usr/bin/env python3
"""Hash the Linux wheels used by the optional sensor-anomaly worker."""

from __future__ import annotations

import argparse
import hashlib
import re
import sys
import zipfile
from email.parser import BytesParser
from pathlib import Path

REQUIREMENT = re.compile(
    r"^(?P<name>[A-Za-z0-9][A-Za-z0-9._-]*)==(?P<version>[A-Za-z0-9][A-Za-z0-9.!+_-]*)"
    r"(?:\s*;\s*(?P<marker>.+))?$"
)


def canonicalize(name: str) -> str:
    return re.sub(r"[-_.]+", "-", name).lower()


def read_resolved(path: Path) -> dict[str, tuple[str, str, str | None]]:
    requirements: dict[str, tuple[str, str, str | None]] = {}
    for number, raw_line in enumerate(path.read_text(encoding="utf-8").splitlines(), 1):
        line = raw_line.strip()
        if not line or line.startswith("#") or line.startswith("-"):
            continue
        line = line.split(" #", 1)[0].strip()
        match = REQUIREMENT.fullmatch(line)
        if match is None:
            raise ValueError(f"{path}:{number}: expected an exact package pin, found {raw_line!r}")
        name = match.group("name")
        version = match.group("version")
        marker = match.group("marker")
        key = canonicalize(name)
        requirement = (name, version, marker)
        previous = requirements.get(key)
        if previous is not None and previous != requirement:
            raise ValueError(f"{path}:{number}: conflicting pins for {name}")
        requirements[key] = requirement
    if not requirements:
        raise ValueError(f"no pinned requirements found in {path}")
    return requirements


def wheel_metadata(path: Path) -> tuple[str, str]:
    with zipfile.ZipFile(path) as wheel:
        metadata_names = [
            name for name in wheel.namelist() if name.endswith(".dist-info/METADATA")
        ]
        if len(metadata_names) != 1:
            raise ValueError(f"{path}: expected one wheel METADATA file")
        message = BytesParser().parsebytes(wheel.read(metadata_names[0]))
    name = message.get("Name")
    version = message.get("Version")
    if not name or not version:
        raise ValueError(f"{path}: wheel METADATA is missing Name or Version")
    return name, version


def wheel_hashes(directory: Path) -> dict[str, tuple[str, set[str]]]:
    found: dict[str, tuple[str, set[str]]] = {}
    for path in sorted(directory.glob("*.whl")):
        name, version = wheel_metadata(path)
        key = canonicalize(name)
        hasher = hashlib.sha256()
        with path.open("rb") as wheel:
            for chunk in iter(lambda: wheel.read(1024 * 1024), b""):
                hasher.update(chunk)
        digest = hasher.hexdigest()
        previous = found.get(key)
        if previous is None:
            found[key] = (version, {digest})
            continue
        if previous[0] != version:
            raise ValueError(f"{directory}: multiple versions found for {name}")
        previous[1].add(digest)
    if not found:
        raise ValueError(f"no wheels found in {directory}")
    return found


def build_lock(
    requirements: dict[str, tuple[str, str, str | None]],
    amd64: dict[str, tuple[str, set[str]]],
    arm64: dict[str, tuple[str, set[str]]],
) -> list[str]:
    lines = [
        "# Generated by scripts/generate_ml_anomaly_runtime_lock.py.",
        "# Versions come from requirements/ml-anomaly-runtime.in; hashes cover the",
        "# binary wheels selected for Linux AMD64 and ARM64 on Python 3.11.",
        "",
    ]
    for key in sorted(requirements):
        name, version, marker = requirements[key]
        amd64_entry = amd64.get(key)
        arm64_entry = arm64.get(key)
        if amd64_entry is None or arm64_entry is None:
            if amd64_entry is None and arm64_entry is None and marker:
                # Non-Linux marker-only dependencies do not belong in this image lock.
                continue
            missing = []
            if amd64_entry is None:
                missing.append("AMD64")
            if arm64_entry is None:
                missing.append("ARM64")
            raise ValueError(f"{name} has no compatible binary wheel for {', '.join(missing)}")
        for architecture, entry in (("AMD64", amd64_entry), ("ARM64", arm64_entry)):
            if entry[0] != version:
                raise ValueError(
                    f"{architecture} wheel for {name} is {entry[0]}, expected pinned {version}"
                )
        hashes = sorted(amd64_entry[1] | arm64_entry[1])
        suffix = f" ; {marker}" if marker else ""
        lines.append(f"{name}=={version}{suffix} \\")
        lines.extend(f"    --hash=sha256:{digest} \\" for digest in hashes[:-1])
        lines.append(f"    --hash=sha256:{hashes[-1]}")
    return lines


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--resolved", type=Path, required=True)
    parser.add_argument("--amd64-wheels", type=Path, required=True)
    parser.add_argument("--arm64-wheels", type=Path, required=True)
    parser.add_argument("--output", type=Path, required=True)
    args = parser.parse_args()
    try:
        requirements = read_resolved(args.resolved)
        amd64 = wheel_hashes(args.amd64_wheels)
        arm64 = wheel_hashes(args.arm64_wheels)
        lines = build_lock(requirements, amd64, arm64)
        args.output.write_text("\n".join(lines) + "\n", encoding="utf-8")
    except (OSError, ValueError, zipfile.BadZipFile) as error:
        print(f"ML runtime lock generation failed: {error}", file=sys.stderr)
        return 1
    locked_count = sum(line.endswith("\\") and "==" in line for line in lines)
    print(f"Wrote {args.output} with {locked_count} hashed package entries")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
