def run(command: list[str], *, timeout: int = 90, check: bool = True):
    result = subprocess.run(command, text=True, capture_output=True, check=False, timeout=timeout)
    if check and result.returncode:
        detail = "\n".join(part for part in (result.stdout, result.stderr) if part)
        raise RuntimeError(f"command failed ({result.returncode}): {' '.join(command[:5])} …\n{detail}")
    return result


def _seed_statements() -> tuple[str, str]:
    source = SEED.read_text(encoding="utf-8")
    pillar = re.search(
        r"(?s)(WITH pillar_seed AS \(.*?ON CONFLICT \(pillar_key\) DO UPDATE SET.*?;)", source
    )
    rubric = re.search(
        r"(?s)(WITH rubric_seed AS \(.*?ON CONFLICT \(pillar_id, score_value, rubric_version\) DO UPDATE SET.*?;)",
        source,
    )
    if pillar is None or rubric is None:
        raise RuntimeError("the curated EBF pillar/rubric seed upserts changed shape")
    return pillar.group(1), rubric.group(1)


def _relation_rls(connection) -> dict[str, tuple[bool, bool]]:
    with connection.cursor() as cursor:
        cursor.execute(
            "SELECT relation.relname, relation.relrowsecurity, relation.relforcerowsecurity "
            "FROM pg_catalog.pg_class AS relation "
            "JOIN pg_catalog.pg_namespace AS namespace ON namespace.oid = relation.relnamespace "
            "WHERE namespace.nspname = 'public' AND relation.relname = ANY(%s) "
            "ORDER BY relation.relname",
            (list(RELATIONS),),
        )
        rows = cursor.fetchall()
    return {name: (enabled, forced) for name, enabled, forced in rows}


def _apply_migration(connection, migration: str) -> None:
    with connection.cursor() as cursor:
        cursor.execute(migration)
    connection.commit()


